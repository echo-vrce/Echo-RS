/// The type name of a message id, if it is one the game registers.
pub fn message_name(id: u64) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<u64, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| NAMES.iter().map(|&n| (mat_sym(n), n)).collect()).get(&id).copied()
}
